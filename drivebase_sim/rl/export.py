"""Export only the deterministic PPO actor, build with Zig, check float32."""

import argparse
import ctypes
import json
import os
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

import numpy as np

from rl.env import OBSERVATION_SCALE, SPEED_LIMIT
from rl.live import atomic_json


def actor_layers(model):
    import torch
    layers = [layer for layer in model.policy.mlp_extractor.policy_net
              if isinstance(layer, torch.nn.Linear)] + [model.policy.action_net]
    if [(layer.in_features, layer.out_features) for layer in layers] != [(32, 64), (64, 64), (64, 6)]:
        raise ValueError('Expected a separate 32-64-64-6 actor')
    return [(layer.weight.detach().cpu().numpy().astype(np.float32),
             layer.bias.detach().cpu().numpy().astype(np.float32)) for layer in layers]


def c_array(name, array):
    values = ','.join(float(value).hex()+'f' for value in array.ravel())
    return f'static const float {name}[{array.size}] = {{{values}}};\n'


def generate(model, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    layers = actor_layers(model)
    header = '''/* Generated deterministic rover actor. Raw physical units in, clipped actions out. */
#ifndef ROVER_POLICY_H
#define ROVER_POLICY_H
#define ROVER_OBSERVATIONS 32
#define ROVER_ACTIONS 6
void rover_policy(const float raw[32], float action[6]);
void rover_targets(const float raw[32], float separation, float radius, float targets[6]);
#endif
'''
    code = '''/* Generated by rl.export; no allocation, runtime normalizer or critic. */
#include "policy.h"
/* Provided by the board's C math library when linking the firmware. */
extern float tanhf(float);
static float clip(float x, float lo, float hi) { return x < lo ? lo : (x > hi ? hi : x); }
'''
    code += c_array('scale', OBSERVATION_SCALE)
    for i, (weight, bias) in enumerate(layers):
        code += c_array(f'w{i}', weight) + c_array(f'b{i}', bias)
    code += '''void rover_policy(const float raw[32], float action[6]) {
    float x[32], h0[64], h1[64];
    for (int i=0; i<32; ++i) x[i] = raw[i]/scale[i];
'''
    for i, (weight, _) in enumerate(layers):
        nout, nin = weight.shape
        source, dest = [('x', 'h0'), ('h0', 'h1'), ('h1', 'action')][i]
        code += f'''    for (int j=0; j<{nout}; ++j) {{
        float v = b{i}[j];
        for (int k=0; k<{nin}; ++k) v += w{i}[j*{nin}+k]*{source}[k];
        {dest}[j] = ''' + ('tanhf(v);' if i < 2 else 'clip(v, -1.0f, 1.0f);') + '\n    }\n'
    code += '''}
void rover_targets(const float raw[32], float separation, float radius, float targets[6]) {
    float action[6];
    rover_policy(raw, action);
    for (int i=0; i<6; ++i) {
        float base = (raw[0] + (i<3 ? -1.0f : 1.0f)*raw[1]*separation*0.5f)/radius;
        targets[i] = clip(base + 5.0f*action[i], -SPEED_LIMIT, SPEED_LIMIT);
    }
}
'''.replace('SPEED_LIMIT', float(np.float32(SPEED_LIMIT)).hex()+'f')
    (out/'policy.h').write_text(header, encoding='utf-8')
    (out/'policy.c').write_text(code, encoding='utf-8')
    return layers


def build(out):
    out = Path(out).resolve()
    host = out/('policy.dll' if os.name == 'nt' else 'policy.so')
    prefix = [sys.executable, '-m', 'ziglang', 'cc']
    commands = [prefix + ['-shared', '-O2', '-ffp-contract=off', str(out/'policy.c'),
                          '-o', str(host)] + ([] if os.name == 'nt' else ['-fPIC', '-lm']),
                # Zig 0.17 names the ISA through -mcpu; its target parser
                # rejects Clang's thumbv7em-none-eabihf architecture spelling.
                prefix + ['-target', 'thumb-freestanding-eabihf', '-mcpu=cortex_m4',
                          '-mfpu=fpv4-sp-d16', '-mfloat-abi=hard', '-O2',
                          '-ffp-contract=off', '-c', str(out/'policy.c'),
                          '-o', str(out/'policy_m4.o')]]
    logs = []
    cache_root = Path(tempfile.gettempdir()) if os.name == 'nt' else out.parent
    cache_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='r4_zig_', dir=cache_root) as temporary:
        cache = Path(temporary).resolve()
        assert cache.is_relative_to(cache_root.resolve())
        names = ('ZIG_GLOBAL_CACHE_DIR', 'ZIG_LOCAL_CACHE_DIR')
        previous = {name: os.environ.get(name) for name in names}
        for name in names:
            os.environ[name] = str(cache/name.lower())
        try:
            for command in commands:
                # Zig on Windows failed about once in three local test runs and
                # passed on rerun; retry so a long Colab run is not lost to it.
                for attempt in range(3):
                    result = subprocess.run(command, capture_output=True, text=True)
                    logs.append(dict(command=command, attempt=attempt,
                                     stdout=result.stdout, stderr=result.stderr))
                    if not result.returncode:
                        break
                else:
                    raise RuntimeError(f'Compiler failed ({result.returncode}): {result.stderr}')
        finally:
            for name, value in previous.items():
                if value is None:
                    del os.environ[name]
                else:
                    os.environ[name] = value
    return host, logs


def elf_sizes(path):
    """Read ELF32 section headers without an extra package or tool install."""
    data = Path(path).read_bytes()
    if data[:5] != b'\x7fELF\x01':
        raise ValueError('Expected a little-endian ELF32 M4 object')
    section_offset = struct.unpack_from('<I', data, 32)[0]
    entry_size, count = struct.unpack_from('<HH', data, 46)
    sizes = dict(text=0, rodata=0, data=0, bss=0)
    for i in range(count):
        _, kind, flags, _, _, size = struct.unpack_from('<6I', data, section_offset+i*entry_size)
        if flags & 2:
            key = 'bss' if kind == 8 else ('text' if flags & 4 else
                                          'data' if flags & 1 else 'rodata')
            sizes[key] += size
    return sizes


def compare(model, library, observations):
    from rl.baselines import LearnedC
    c = LearnedC(Path(library).resolve())
    expected = model.predict(np.asarray(observations, dtype=np.float32), deterministic=True)[0]
    actual = np.asarray([c.predict(row)[0] for row in observations])
    return float(np.max(np.abs(expected-actual)))


def export(model_path, out, observation_path=None):
    import torch
    from stable_baselines3 import PPO
    torch.set_num_threads(1)
    model = PPO.load(model_path, device='cpu')
    layers = generate(model, out)
    host, logs = build(out)
    rng = np.random.default_rng(630001)
    random_obs = rng.uniform(-2, 2, (10000, 32)).astype(np.float32)
    random_error = compare(model, host, random_obs)
    report = dict(model=str(model_path), random_observations=10000,
        random_max_abs_error=random_error, matrix_max_abs_error=None,
        matrix_observations=0, compile=logs, m4_object_sections_bytes=elf_sizes(Path(out)/'policy_m4.o'),
        parameters=sum(w.size+b.size for w, b in layers),
        multiply_adds=sum(w.size for w, _ in layers), tanhf_calls=128,
        stack_arrays_bytes=(32+64+64)*4,
        requested_cortex_target='thumbv7em-none-eabihf cortex-m4 fpv4-sp-d16 hard-float',
        zig_target='thumb-freestanding-eabihf with cortex_m4 (ARMv7E-M)',
        estimated_time_us_at_170MHz=dict(lower=150., upper=600., measured=False),
        timing_basis='6528 MACs at 2-6 cycles plus 128 library tanhf calls at 100-500 cycles; no board measurement')
    if observation_path:
        with np.load(observation_path) as data:
            observations = data['observations']
        if len(observations) < 10000:
            raise ValueError('Matrix equivalence requires at least 10000 observations')
        selected = observations[rng.choice(len(observations), 10000, replace=False)]
        report.update(matrix_max_abs_error=compare(model, host, selected),
                      matrix_observations=10000)
    atomic_json(Path(out)/'export.json', report)
    if random_error > 1e-5 or (report['matrix_max_abs_error'] or 0) > 1e-5:
        raise AssertionError('C/PyTorch action difference exceeds 1e-5')
    print(json.dumps(report, indent=2))
    return host


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=Path('rl/export'))
    parser.add_argument('--observations', type=Path)
    args = parser.parse_args()
    export(args.model, args.out, args.observations)
